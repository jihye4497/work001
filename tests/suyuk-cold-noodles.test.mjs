import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {applyCalculationBasis} from '../js/recipe-calculation-basis.js';
import {applyRecipeDisplayNames} from '../js/recipe-display-names.js';
import {aggregate,totalText} from '../js/shopping-list.js';
import {validateData} from '../js/ingredients.js';
const read=async name=>JSON.parse(await readFile(new URL('../data/'+name,import.meta.url),'utf8'));
const [ingredients,raw]=await Promise.all(['ingredients.json','recipes.json'].map(read));
const snapshot=JSON.stringify(raw),id='mincook-blog-442';
const recipe=applyCalculationBasis(applyRecipeDisplayNames(raw)).find(r=>r.id===id);
test('양지수육12인분·원래7행 유지하며 냉면5행은 미기재로 추가하고 개별제외',()=>{
 validateData(ingredients,[recipe]);
 assert.equal(recipe.baseServings,12);assert.equal(recipe.name,'양지수육 & 평양냉면');
 assert.equal(recipe.components[0].mode,'servings');assert.equal(recipe.components[1].usesComponentId,'suyuk');
 assert.deepEqual(recipe.ingredients.filter(i=>i.componentId==='suyuk').map(({componentId,...i})=>i),raw.find(r=>r.id===id).ingredients);
 const additional=recipe.ingredients.filter(i=>i.componentId==='cold-noodles');
 assert.equal(additional.length,5);assert.ok(additional.every(i=>i.amount===null&&i.unit===null));
 const rows=counts=>aggregate(ingredients,[recipe],[{recipeId:id,times:1,servings:12,componentBatches:counts}],12);
 assert.equal(totalText(rows({}).find(r=>r.ingredient.name==='소고기 양지')),'3kg');
 assert.equal(rows({}).filter(r=>r.ingredient.name==='소고기 양지').length,1);
 assert.ok(rows({}).some(r=>r.ingredient.name==='메밀면'&&r.unknown));
 const without=rows({'cold-noodles':0});
 assert.ok(!without.some(r=>r.ingredient.name==='메밀면'));
 assert.ok(without.some(r=>r.ingredient.name==='소면'&&r.unknown));
 assert.equal(totalText(without.find(r=>r.ingredient.name==='소고기 양지')),'3kg');
 assert.equal(JSON.stringify(raw),snapshot);
 assert.deepEqual(applyCalculationBasis([recipe])[0],recipe);
});
